// GetCatalogFinding retrieves standard rule metadata for a given rule ID.
func GetCatalogFinding(id string) (model.Finding, bool) {
	key := strings.ToUpper(strings.TrimSpace(id))
	f, ok := standardCatalog[key]
	return f, ok
}

// AllCatalogFindings returns all standard rule definitions.
func AllCatalogFindings() []model.Finding {
	res := make([]model.Finding, 0, len(standardCatalog))
	for _, f := range standardCatalog {
		res = append(res, f)
	}
	return res
}
